#!/usr/bin/env python3
"""Frame storyboard extraction — one frame per scene.

Scene rules (from CLAUDE.md):
  - A scene = one continuous segment likely generated by a video model in a
    single run (1-15s typical). A 30s talking head with no cuts = one scene.
  - Overlays/underlays read as their own scenes (they change enough of the
    frame to trip detection).
  - One frame per scene. Movement within a scene (props appearing, setting
    changes) shows up as extra detected scenes — which satisfies the
    multiple-frames-for-movement exception naturally.

Output (into the V-folder):
  frames/scene_01_0.0s.jpg ... one jpg per scene, timestamp in the name
  storyboard.jpg            ... contact sheet (all scenes tiled in order)

Usage:
  python3 storyboard.py --video <path> --out <v_folder> [--row N]
                        [--threshold 0.27] [--min-scene 0.8]

Called automatically by new_video.py after download.
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path


def probe_duration(video: Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "quiet", "-show_entries", "format=duration",
         "-of", "csv=p=0", str(video)],
        capture_output=True, text=True, check=True)
    return float(out.stdout.strip())


def detect_cuts(video: Path, threshold: float) -> list[float]:
    """Return timestamps where ffmpeg detects a scene change."""
    cmd = ["ffmpeg", "-i", str(video), "-vf",
           f"select='gt(scene,{threshold})',metadata=print",
           "-an", "-f", "null", "-"]
    out = subprocess.run(cmd, capture_output=True, text=True)
    cuts = []
    for line in out.stderr.splitlines():
        m = re.search(r"pts_time:([\d.]+)", line)
        if m:
            cuts.append(float(m.group(1)))
    return sorted(set(cuts))


def build_scenes(cuts: list[float], duration: float, min_scene: float) -> list[tuple[float, float]]:
    """Cut points → (start, end) segments; merge sub-min_scene jitter."""
    bounds = [0.0] + [t for t in cuts if 0.0 < t < duration] + [duration]
    scenes = []
    start = bounds[0]
    for end in bounds[1:]:
        if end - start >= min_scene:
            scenes.append((start, end))
            start = end
        # else: too short — extend current scene past this cut (flash/jitter)
    if scenes and scenes[-1][1] < duration:
        s, _ = scenes[-1]
        scenes[-1] = (s, duration)
    if not scenes:
        scenes = [(0.0, duration)]
    return scenes


def extract_frame(video: Path, t: float, dest: Path):
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-ss", f"{t:.3f}", "-i", str(video),
         "-frames:v", "1", "-q:v", "2", str(dest)],
        check=True)


def contact_sheet(frames: list[Path], dest: Path):
    if not frames:
        return
    cols = 4
    rows = (len(frames) + cols - 1) // cols
    # pad input list so the tile grid is full
    inputs = []
    for f in frames:
        inputs += ["-i", str(f)]
    n = len(frames)
    filt = "".join(f"[{i}:v]scale=270:480[v{i}];" for i in range(n))
    filt += "".join(f"[v{i}]" for i in range(n))
    filt += f"xstack=inputs={n}:layout=" + "|".join(
        f"{(i % cols) * 270}_{(i // cols) * 480}" for i in range(n)) + "[out]"
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error", *inputs, "-filter_complex", filt,
         "-map", "[out]", "-frames:v", "1", "-q:v", "3", str(dest)],
        check=False)


def main():
    ap = argparse.ArgumentParser(description="One frame per scene, by the engine's scene rules")
    ap.add_argument("--video", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path, help="V-folder")
    ap.add_argument("--row", type=int, help="Master DB row (for logging only, for now)")
    ap.add_argument("--threshold", type=float, default=0.18,
                    help="Scene-change sensitivity. Lower = more scenes (catches partial overlays). Default 0.18")
    ap.add_argument("--min-scene", type=float, default=0.8,
                    help="Merge segments shorter than this many seconds (transition jitter)")
    ap.add_argument("--two-frame-over", type=float, default=6.0,
                    help="Scenes longer than this get TWO frames (movement exception). Default 6s")
    args = ap.parse_args()

    if not args.video.exists():
        sys.exit(f"Video not found: {args.video}")

    duration = probe_duration(args.video)
    cuts = detect_cuts(args.video, args.threshold)
    scenes = build_scenes(cuts, duration, args.min_scene)

    frames_dir = args.out / "frames"
    frames_dir.mkdir(parents=True, exist_ok=True)
    for old in frames_dir.glob("scene_*.jpg"):
        old.unlink()

    frame_paths = []
    for i, (start, end) in enumerate(scenes, 1):
        length = end - start
        if length > args.two_frame_over:
            # Movement exception: long scene → early + late frame
            points = [(start + 0.30 * length, "a"), (start + 0.75 * length, "b")]
        else:
            points = [(start + 0.4 * length, "")]   # 40% in — clear of transitions
        for t, tag in points:
            dest = frames_dir / f"scene_{i:02d}{tag}_{t:.1f}s.jpg"
            extract_frame(args.video, t, dest)
            frame_paths.append(dest)

    sheet = args.out / "storyboard.jpg"
    contact_sheet(frame_paths, sheet)

    print(json.dumps({
        "duration_s": round(duration, 1),
        "cuts_detected": len(cuts),
        "scenes": len(scenes),
        "scene_bounds": [[round(s, 1), round(e, 1)] for s, e in scenes],
        "frames_dir": str(frames_dir),
        "contact_sheet": str(sheet),
    }, indent=2))


if __name__ == "__main__":
    main()
